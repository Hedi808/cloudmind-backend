from datetime import datetime
from pathlib import Path

from fastapi import APIRouter, HTTPException

from app.agents.git_agent import GitAgent
from app.schemas.git import GitTestPublishRequest, GitTestPublishResponse
from app.tools.git_tools import sanitize_repo_name

router = APIRouter(prefix="/git", tags=["Git"])

git_agent = GitAgent()


@router.post("/test-publish", response_model=GitTestPublishResponse)
def test_publish_to_repository(request: GitTestPublishRequest):
    """
    Safe GitAgent test.

    It creates a small test file, commits it to a CloudMind branch,
    pushes that branch, and opens a pull request.
    """
    try:
        repo_name = sanitize_repo_name(request.repo_url)
        local_repo_path = Path("workspace/repos") / repo_name

        clone_result = git_agent.clone_for_write(
            repo_url=request.repo_url,
            local_repo_path=str(local_repo_path),
            branch=request.base_branch,
        )

        test_file = local_repo_path / "cloudmind-git-test.md"

        timestamp = datetime.utcnow().isoformat()

        test_file.write_text(
            "# CloudMind GitAgent Test\n\n"
            f"This file was generated by CloudMind at `{timestamp} UTC`.\n\n"
            "Purpose: verify that CloudMind can safely create a branch, "
            "commit changes, push to GitHub, and open a pull request.\n",
            encoding="utf-8",
        )

        branch_name = "cloudmind/git-agent-test"

        result = git_agent.publish_deployment_changes(
            local_repo_path=str(local_repo_path),
            repo_url=request.repo_url,
            generated_files=["cloudmind-git-test.md"],
            base_branch=request.base_branch,
            branch_name=branch_name,
        )

        return GitTestPublishResponse(
            status="success",
            message="GitAgent test completed successfully.",
            result={
                "clone": clone_result,
                "publish": result,
            },
        )

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"GitAgent test failed: {exc}",
        ) from exc