import base64
import os
import re
import shutil
import stat
import time
from pathlib import Path
from typing import Any
from urllib.parse import quote, urlparse

import requests
from git import GitCommandError, Repo

from app.core.config import settings


class GitAgent:
    """
    Controlled Git agent for CloudMind.

    Phase 20D:
    - Publishing generated files now uses GitHub API directly.
    - No local git add.
    - No local commit.
    - No local push.
    - No persistent local repository publishing flow.

    Older local Git methods are kept for backward compatibility, but ToolRegistry now uses
    publish_generated_file_contents().
    """

    def __init__(self):
        self.github_token = settings.github_token
        self.github_username = settings.github_username

    # -------------------------------------------------------------------------
    # Remote GitOps publishing mode
    # -------------------------------------------------------------------------

    def publish_generated_file_contents(
        self,
        repo_url: str,
        source_repo_path: str,
        generated_files: list[str | dict[str, Any]],
        base_branch: str = "main",
        branch_name: str = "cloudmind/deployment-files",
        commit_message: str = "chore: add CloudMind generated files",
        pull_request_title: str = "Add CloudMind generated files",
        pull_request_body: str | None = None,
    ) -> dict[str, Any]:
        """
        Remote GitOps flow:
        1. Read generated file contents from temporary local generation folder.
        2. Create a branch on GitHub from base_branch.
        3. Create/update each file through GitHub Contents API.
        4. Open a pull request.

        This avoids:
        - git add
        - git commit
        - git push
        - local branch state
        - Windows repo folder locks during publishing
        """
        if not self.github_token:
            raise RuntimeError("GITHUB_TOKEN is missing in .env")

        owner, repo_name = self._parse_github_owner_repo(repo_url)
        safe_branch_name = self._sanitize_branch_name(branch_name)
        source_path = Path(source_repo_path)

        file_payloads = self._build_file_payloads(
            source_repo_path=source_path,
            generated_files=generated_files,
        )

        if not file_payloads:
            return {
                "status": "no_changes",
                "message": "No generated file contents were found to publish.",
                "branch": safe_branch_name,
                "files": [],
            }

        base_sha = self._get_branch_sha(
            owner=owner,
            repo_name=repo_name,
            branch=base_branch,
        )

        branch_result = self._create_remote_branch(
            owner=owner,
            repo_name=repo_name,
            branch_name=safe_branch_name,
            base_sha=base_sha,
        )

        committed_files = []

        for file_payload in file_payloads:
            commit_result = self._put_file_contents(
                owner=owner,
                repo_name=repo_name,
                branch_name=safe_branch_name,
                path=file_payload["path"],
                content=file_payload["content"],
                message=f"{commit_message}: {file_payload['path']}",
            )
            committed_files.append(
                {
                    "path": file_payload["path"],
                    "sha": commit_result.get("content", {}).get("sha"),
                    "commit_sha": commit_result.get("commit", {}).get("sha"),
                    "html_url": commit_result.get("content", {}).get("html_url"),
                }
            )

        pr_result = self.open_pull_request(
            repo_url=repo_url,
            branch_name=safe_branch_name,
            title=pull_request_title,
            body=pull_request_body
            or (
                "This pull request was generated by CloudMind.\n\n"
                "It contains deployment-related files generated from repository analysis.\n\n"
                "Publishing was done through GitHub API remote GitOps mode."
            ),
            base_branch=base_branch,
        )

        return {
            "status": "published",
            "mode": "remote_github_api",
            "branch": safe_branch_name,
            "base_branch": base_branch,
            "base_sha": base_sha,
            "branch_result": branch_result,
            "files": committed_files,
            "pull_request": pr_result,
        }

    def _build_file_payloads(
        self,
        source_repo_path: Path,
        generated_files: list[str | dict[str, Any]],
    ) -> list[dict[str, str]]:
        payloads: list[dict[str, str]] = []
        seen_paths: set[str] = set()

        for generated_file in generated_files:
            relative_path: str | None = None
            raw_path: str | None = None
            inline_content: str | None = None

            if isinstance(generated_file, str):
                raw_path = generated_file
                relative_path = generated_file

            elif isinstance(generated_file, dict):
                inline_content = generated_file.get("content")
                relative_path = (
                    generated_file.get("relative_path")
                    or generated_file.get("repo_path")
                    or generated_file.get("path_in_repo")
                )
                raw_path = generated_file.get("path") or relative_path

            if not relative_path and raw_path:
                relative_path = self._make_repo_relative_path(
                    source_repo_path=source_repo_path,
                    raw_path=raw_path,
                )

            if not relative_path:
                continue

            normalized_repo_path = self._normalize_repo_file_path(relative_path)

            if not normalized_repo_path or normalized_repo_path in seen_paths:
                continue

            content = inline_content

            if content is None:
                file_path = self._resolve_generated_file_path(
                    source_repo_path=source_repo_path,
                    raw_path=raw_path or normalized_repo_path,
                )

                if not file_path.exists() or not file_path.is_file():
                    raise FileNotFoundError(
                        f"Generated file not found for remote publish: {file_path}"
                    )

                content = file_path.read_text(encoding="utf-8", errors="ignore")

            payloads.append(
                {
                    "path": normalized_repo_path,
                    "content": content,
                }
            )
            seen_paths.add(normalized_repo_path)

        return payloads

    def _resolve_generated_file_path(
        self,
        source_repo_path: Path,
        raw_path: str,
    ) -> Path:
        path = Path(raw_path)

        if path.is_absolute():
            return path

        source_text = source_repo_path.as_posix().rstrip("/")
        path_text = path.as_posix()

        if path_text == source_text or path_text.startswith(source_text + "/"):
            return path

        return source_repo_path / path

    def _make_repo_relative_path(
        self,
        source_repo_path: Path,
        raw_path: str,
    ) -> str:
        path = Path(raw_path)

        try:
            return path.relative_to(source_repo_path).as_posix()
        except ValueError:
            return path.as_posix()

    def _normalize_repo_file_path(self, path: str) -> str:
        path = path.replace("\\", "/").strip()

        while path.startswith("./"):
            path = path[2:]

        path = path.strip("/")

        if not path:
            return ""

        if ".." in Path(path).parts:
            raise ValueError(f"Unsafe generated file path: {path}")

        return path

    def _get_branch_sha(
        self,
        owner: str,
        repo_name: str,
        branch: str,
    ) -> str:
        api_url = (
            f"https://api.github.com/repos/{owner}/{repo_name}/git/ref/"
            f"heads/{quote(branch, safe='')}"
        )

        response = requests.get(
            api_url,
            headers=self._github_headers(),
            timeout=30,
        )

        if response.status_code != 200:
            raise RuntimeError(
                f"Failed to get base branch ref: {response.status_code} {response.text}"
            )

        data = response.json()
        sha = data.get("object", {}).get("sha")

        if not sha:
            raise RuntimeError(f"Base branch SHA not found for branch: {branch}")

        return sha

    def _create_remote_branch(
        self,
        owner: str,
        repo_name: str,
        branch_name: str,
        base_sha: str,
    ) -> dict[str, Any]:
        api_url = f"https://api.github.com/repos/{owner}/{repo_name}/git/refs"

        payload = {
            "ref": f"refs/heads/{branch_name}",
            "sha": base_sha,
        }

        response = requests.post(
            api_url,
            headers=self._github_headers(),
            json=payload,
            timeout=30,
        )

        if response.status_code in [200, 201]:
            return {
                "status": "branch_created",
                "branch": branch_name,
                "data": response.json(),
            }

        if response.status_code == 422 and "Reference already exists" in response.text:
            return {
                "status": "branch_exists",
                "branch": branch_name,
                "data": response.json(),
            }

        raise RuntimeError(
            f"Failed to create remote branch: {response.status_code} {response.text}"
        )

    def _get_file_sha_on_branch(
        self,
        owner: str,
        repo_name: str,
        branch_name: str,
        path: str,
    ) -> str | None:
        encoded_path = quote(path, safe="/")
        api_url = f"https://api.github.com/repos/{owner}/{repo_name}/contents/{encoded_path}"

        response = requests.get(
            api_url,
            headers=self._github_headers(),
            params={"ref": branch_name},
            timeout=30,
        )

        if response.status_code == 404:
            return None

        if response.status_code != 200:
            raise RuntimeError(
                f"Failed to inspect remote file {path}: {response.status_code} {response.text}"
            )

        data = response.json()

        if isinstance(data, dict):
            return data.get("sha")

        return None

    def _put_file_contents(
        self,
        owner: str,
        repo_name: str,
        branch_name: str,
        path: str,
        content: str,
        message: str,
    ) -> dict[str, Any]:
        encoded_path = quote(path, safe="/")
        api_url = f"https://api.github.com/repos/{owner}/{repo_name}/contents/{encoded_path}"

        existing_sha = self._get_file_sha_on_branch(
            owner=owner,
            repo_name=repo_name,
            branch_name=branch_name,
            path=path,
        )

        payload: dict[str, Any] = {
            "message": message,
            "content": base64.b64encode(content.encode("utf-8")).decode("ascii"),
            "branch": branch_name,
        }

        if existing_sha:
            payload["sha"] = existing_sha

        response = requests.put(
            api_url,
            headers=self._github_headers(),
            json=payload,
            timeout=60,
        )

        if response.status_code not in [200, 201]:
            raise RuntimeError(
                f"Failed to create/update remote file {path}: {response.status_code} {response.text}"
            )

        return response.json()

    def _github_headers(self) -> dict[str, str]:
        if not self.github_token:
            raise RuntimeError("GITHUB_TOKEN is missing in .env")

        return {
            "Authorization": f"Bearer {self.github_token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        }

    # -------------------------------------------------------------------------
    # Older local Git methods kept for compatibility
    # -------------------------------------------------------------------------

    def clone_for_write(
        self,
        repo_url: str,
        local_repo_path: str,
        branch: str | None = None,
    ) -> dict[str, Any]:
        if not self.github_token:
            raise RuntimeError("GITHUB_TOKEN is missing in .env")

        repo_path = Path(local_repo_path)

        if repo_path.exists():
            self._safe_delete_folder(repo_path)

        repo_path.parent.mkdir(parents=True, exist_ok=True)

        public_url = self._normalize_repo_url(repo_url)
        authenticated_url = self._build_authenticated_url(public_url)

        try:
            clone_kwargs = {
                "multi_options": ["--depth=1"],
            }

            if branch:
                clone_kwargs["branch"] = branch

            repo = Repo.clone_from(authenticated_url, repo_path, **clone_kwargs)
            repo.remote(name="origin").set_url(public_url)

            return {
                "status": "cloned",
                "local_path": str(repo_path),
                "branch": branch or repo.active_branch.name,
            }

        except GitCommandError as exc:
            raise RuntimeError(f"Failed to clone repository for write: {exc}") from exc

    def pull_latest(self, local_repo_path: str, branch: str | None = None) -> dict[str, Any]:
        repo_path = Path(local_repo_path)

        if not repo_path.exists():
            raise FileNotFoundError(f"Repository path not found: {repo_path}")

        repo = Repo(repo_path)

        if repo.bare:
            raise RuntimeError("Repository is bare and cannot be used for working tree operations.")

        origin = repo.remote(name="origin")

        if branch:
            self._checkout_branch(repo, branch)

        try:
            pull_result = origin.pull()
        except GitCommandError as exc:
            raise RuntimeError(f"Failed to pull latest changes: {exc}") from exc

        return {
            "status": "pulled",
            "branch": repo.active_branch.name,
            "result": [str(item) for item in pull_result],
        }

    def create_branch(self, local_repo_path: str, branch_name: str) -> dict[str, Any]:
        repo = Repo(Path(local_repo_path))
        safe_branch_name = self._sanitize_branch_name(branch_name)

        existing_branches = [head.name for head in repo.heads]

        if safe_branch_name in existing_branches:
            repo.git.checkout(safe_branch_name)
        else:
            repo.git.checkout("-b", safe_branch_name)

        return {
            "status": "branch_ready",
            "branch": safe_branch_name,
        }

    def commit_changes(
        self,
        local_repo_path: str,
        commit_message: str,
        files_to_add: list[str] | None = None,
    ) -> dict[str, Any]:
        repo_path = Path(local_repo_path)
        repo = Repo(repo_path)

        self._ensure_git_identity(repo)

        if files_to_add:
            for file_path in files_to_add:
                repo.git.add(file_path)
        else:
            repo.git.add(A=True)

        if not repo.is_dirty(untracked_files=True):
            return {
                "status": "no_changes",
                "message": "No changes to commit.",
            }

        commit = repo.index.commit(commit_message)

        return {
            "status": "committed",
            "commit": commit.hexsha,
            "message": commit_message,
        }

    def push_branch(
        self,
        local_repo_path: str,
        branch_name: str,
        repo_url: str,
    ) -> dict[str, Any]:
        if not self.github_token:
            raise RuntimeError("GITHUB_TOKEN is missing in .env")

        repo = Repo(Path(local_repo_path))
        safe_branch_name = self._sanitize_branch_name(branch_name)

        public_url = self._normalize_repo_url(repo_url)
        authenticated_url = self._build_authenticated_url(public_url)

        origin = repo.remote(name="origin")
        original_url = origin.url

        try:
            origin.set_url(authenticated_url)

            push_result = repo.git.push(
                "--set-upstream",
                "origin",
                safe_branch_name,
            )

            return {
                "status": "pushed",
                "branch": safe_branch_name,
                "result": push_result,
            }

        except GitCommandError as exc:
            raise RuntimeError(f"Failed to push branch: {exc}") from exc

        finally:
            origin.set_url(original_url or public_url)

    def open_pull_request(
        self,
        repo_url: str,
        branch_name: str,
        title: str,
        body: str,
        base_branch: str = "main",
    ) -> dict[str, Any]:
        if not self.github_token:
            raise RuntimeError("GITHUB_TOKEN is missing in .env")

        owner, repo_name = self._parse_github_owner_repo(repo_url)

        api_url = f"https://api.github.com/repos/{owner}/{repo_name}/pulls"

        payload = {
            "title": title,
            "head": branch_name,
            "base": base_branch,
            "body": body,
        }

        response = requests.post(
            api_url,
            headers=self._github_headers(),
            json=payload,
            timeout=30,
        )

        if response.status_code not in [200, 201]:
            raise RuntimeError(
                f"Failed to open pull request: {response.status_code} {response.text}"
            )

        data = response.json()

        return {
            "status": "pull_request_created",
            "number": data.get("number"),
            "url": data.get("html_url"),
            "title": data.get("title"),
        }

    def publish_deployment_changes(
        self,
        local_repo_path: str,
        repo_url: str,
        generated_files: list[str] | None = None,
        base_branch: str = "main",
        branch_name: str = "cloudmind/deployment-files",
    ) -> dict[str, Any]:
        """
        Compatibility wrapper.

        New behavior:
        - Reads generated files from local_repo_path.
        - Publishes them remotely through GitHub Contents API.
        - Does not call git add/commit/push.
        """
        return self.publish_generated_file_contents(
            repo_url=repo_url,
            source_repo_path=local_repo_path,
            generated_files=generated_files or [],
            base_branch=base_branch,
            branch_name=branch_name,
            commit_message="chore: add CloudMind deployment files",
            pull_request_title="Add CloudMind deployment files",
            pull_request_body=(
                "This pull request was generated by CloudMind.\n\n"
                "It contains deployment-related files generated from repository analysis.\n\n"
                "CloudMind used Remote GitOps Mode through the GitHub API."
            ),
        )

    def _checkout_branch(self, repo: Repo, branch: str) -> None:
        local_branches = [head.name for head in repo.heads]

        if branch in local_branches:
            repo.git.checkout(branch)
            return

        remote_branch = f"origin/{branch}"
        remote_refs = [ref.name for ref in repo.remote().refs]

        if remote_branch in remote_refs:
            repo.git.checkout("-b", branch, "--track", remote_branch)
            return

        raise RuntimeError(f"Branch '{branch}' was not found locally or on origin.")

    def _build_authenticated_url(self, repo_url: str) -> str:
        if not self.github_token:
            raise RuntimeError("GITHUB_TOKEN is missing in .env")

        parsed = urlparse(repo_url)

        if parsed.scheme != "https":
            raise ValueError("Only HTTPS GitHub repository URLs are supported for token auth.")

        return f"https://x-access-token:{self.github_token}@{parsed.netloc}{parsed.path}"

    def _normalize_repo_url(self, repo_url: str) -> str:
        repo_url = repo_url.strip()

        if repo_url.endswith(".git"):
            return repo_url

        return repo_url + ".git"

    def _parse_github_owner_repo(self, repo_url: str) -> tuple[str, str]:
        parsed = urlparse(repo_url)
        parts = parsed.path.strip("/").split("/")

        if len(parts) < 2:
            raise ValueError("Invalid GitHub repository URL.")

        owner = parts[0]
        repo_name = parts[1]

        if repo_name.endswith(".git"):
            repo_name = repo_name[:-4]

        return owner, repo_name

    def _sanitize_branch_name(self, branch_name: str) -> str:
        branch_name = branch_name.strip().replace(" ", "-")
        branch_name = re.sub(r"[^a-zA-Z0-9/_-]", "", branch_name)

        if not branch_name:
            branch_name = "cloudmind/deployment-files"

        return branch_name

    def _ensure_git_identity(self, repo: Repo) -> None:
        username = self.github_username or "cloudmind-bot"

        repo.git.config("user.name", username)
        repo.git.config("user.email", f"{username}@users.noreply.github.com")

    def _safe_delete_folder(self, folder_path: Path) -> None:
        def remove_readonly(func, path, exc_info):
            os.chmod(path, stat.S_IWRITE)
            func(path)

        for attempt in range(3):
            try:
                shutil.rmtree(folder_path, onexc=remove_readonly)
                return
            except TypeError:
                shutil.rmtree(folder_path, onerror=remove_readonly)
                return
            except PermissionError:
                if attempt == 2:
                    raise
                time.sleep(1)